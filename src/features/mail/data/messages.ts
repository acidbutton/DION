function dateOffsetForLastMonth(): number {
  const now = new Date();
  const target = new Date(now.getFullYear(), now.getMonth() - 1, 22);
  const diff = Math.round((now.getTime() - target.getTime()) / (1000 * 60 * 60 * 24));
  return Math.max(diff, 3);
}

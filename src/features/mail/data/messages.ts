import type { MailAttachment, MailMessage } from '../types';

function daysAgo(days: number, hours = 11, minutes = 30): Date {
  const date = new Date();
  date.setDate(date.getDate() - days);
  date.setHours(hours, minutes, 0, 0);
  return date;
}

function files(...list: Array<[string, number, MailAttachment['kind']]>): MailAttachment[] {
  return list.map(([name, sizeKb, kind], index) => ({ id: `${name}-${index}`, name, sizeKb, kind }));
}

